//! Manual presets, provider metrics and metric menu from Ritual Desktop's habit-selection catalog.
pub(super) struct Source {
    pub label: &'static str,
    pub group: &'static str,
    pub icon: &'static str,
    pub presets: &'static [(&'static str, &'static str)],
}
impl Source {
    pub fn device(&self) -> bool { self.group == "Devices" || self.label == "Computer Use" }
    pub fn category(&self) -> &'static str {
        if self.label == "Learning" { "Education" } else if self.device() { "Manual" } else { self.label }
    }
}

